"""Generate the three small fictional AWS starter systems into examples/starter-systems/.

    python tools/generate_samples.py

Uses the runtime's `examples` command (C4 levels 1-4, all five overview styles and the AWS
deployment) in Mermaid, Draw.io and PNG, and adds SVG for every view. The systems share their
component and code views, so a file that is byte-identical to the same path under
order-platform is written only once, there.
"""

from pathlib import Path
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "skills/architecture-suite-runtime/scripts"))
from architecture_suite.cli import main as cli  # noqa: E402
from architecture_suite.examples import example_model  # noqa: E402
from architecture_suite.renderers import diagram_specs, render_svg  # noqa: E402
from sample_dedupe import drop_identical  # noqa: E402

NAMES = ("order-platform", "research-portal", "telemetry-platform")
README = """# Starter systems (fictional)

Three small AWS systems, generated by `python tools/generate_samples.py`. Their component and
code views (`03-components`, `04-code`) are the same, and so is any other file that matches
byte for byte. Each such file exists once, under `order-platform/`; look there for the others.
The order platform's model is `../cli-features/model.json`. All facts are illustrative.
"""


def main():
    final = ROOT / "examples/starter-systems"
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp) / "starter-systems"
        status = cli(
            [
                "examples",
                "--output",
                str(stage),
                "--overview-style",
                "all",
                "--format",
                "mermaid,drawio,png",
                "--confirm-write",
                "--confirm-overwrite",
            ]
        )
        if status:
            raise SystemExit(status)
        for index, name in enumerate(NAMES):
            model = example_model(index)
            for base, view in diagram_specs(model, ["all"]):
                (stage / name / (base + ".svg")).write_text(
                    render_svg(model, view), encoding="utf-8", newline="\n"
                )
        for name in NAMES[1:]:
            drop_identical(stage / NAMES[0], stage / name)
        # Same content as examples/cli-features/model.json.
        (stage / NAMES[0] / "architecture-model.json").unlink()
        (stage / "README.md").write_text(README, encoding="utf-8", newline="\n")
        if final.exists():
            shutil.rmtree(final)
        shutil.copytree(
            stage, final, ignore=shutil.ignore_patterns(".architecture-suite-manifest.json")
        )


if __name__ == "__main__":
    main()
